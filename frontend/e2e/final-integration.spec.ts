import { expect, test } from '@playwright/test';
import type { EmployeeDetail, LeaveType, RequestDetail } from '../src/api/types';
import { apiGet, apiPost, goTo, openDetails, pick } from './helpers';

test('final integration: sensitive question and answer appear in the manager card and Messages', async ({ page }) => {
  await page.goto('/');
  await expect(page.getByRole('heading', { level: 1 })).toHaveText('Try the demo');
  await pick(page, 'Alexei');
  const types = await apiGet<LeaveType[]>(page, '/leave-types');
  const created = await apiPost(page, '/requests', { leave_type_id: types.find(t => t.code === 'SICK')!.id, start_date: '2026-11-09', end_date: '2026-11-10', note: 'Private reason' });
  expect(created.status).toBe(200);
  const draft = JSON.parse(created.body) as RequestDetail;
  expect((await apiPost(page, `/requests/${draft.id}/submit`, { expected_version: draft.version })).status).toBe(200);
  expect((await apiPost(page, `/requests/${draft.id}/messages`, { body: 'Private comment' })).status).toBe(200);
  await pick(page, 'Olga');
  const row = page.locator('.queue-row').filter({ has: page.locator(`button[aria-controls="request-${draft.id}"]`) });
  await row.locator('.queue-row-toggle').click();
  await row.getByRole('button', { name: 'Ask a question…', exact: true }).click();
  await row.getByLabel('Your question').fill('Are both dates confirmed?');
  await row.getByRole('button', { name: 'Send question', exact: true }).click();
  await openDetails(page, 'Waiting for the employee');
  await row.locator('.queue-row-toggle').click();
  await expect(row.locator('.dc')).toContainText('Are both dates confirmed?');
  await pick(page, 'Alexei');
  await page.getByLabel('Your answer').fill('Both dates are confirmed.');
  await page.getByRole('button', { name: 'Send answer', exact: true }).click();
  await pick(page, 'Olga');
  await row.locator('.queue-row-toggle').click();
  await expect(row.locator('.dc')).toContainText('Are both dates confirmed?');
  await expect(row.locator('.dc')).toContainText('Both dates are confirmed.');
  await expect(row.locator('.dc')).not.toContainText('Private comment');
  await goTo(page, `/requests/${draft.id}`);
  await openDetails(page, 'Messages');
  const messages = page.locator('.rq-messages');
  await expect(messages).toContainText('Are both dates confirmed?');
  await expect(messages).toContainText('Both dates are confirmed.');
  await expect(page.locator('main')).not.toContainText('Private reason');
  await expect(messages).not.toContainText('Private comment');
});

test('final integration: correction notice shares badge count and changed day length is explained', async ({ page }) => {
  await page.goto('/'); await pick(page, 'David');
  const badge = page.getByRole('navigation', { name: 'Main', exact: true }).getByRole('link', { name: /^Balances/ }).locator('.nav-count');
  await expect(badge).toHaveText('1');
  await expect(page.locator('main')).toContainText('1 balance correction waiting for you — Review');
  await page.locator('main').getByRole('link', { name: 'Review', exact: true }).click();
  await expect(page).toHaveURL(/\/balances$/);
  await expect(page.getByRole('region', { name: 'Corrections waiting for you' })).toContainText('Sam Oduya');
  await pick(page, 'Maria');
  const people = await apiGet<{ items: EmployeeDetail[] }>(page, '/employees');
  const ben = people.items.find(e => e.full_name === 'Ben Carter')!;
  const detail = await apiGet<EmployeeDetail>(page, `/employees/${ben.id}`);
  expect((await apiPost(page, `/employees/${ben.id}/schedule`, { expected_version: detail.version, schedule_id: 2, valid_from: '2026-10-08' })).status).toBe(200);
  await goTo(page, `/balances/${ben.id}/explain?leave_type_id=1`);
  await expect(page.getByRole('heading', { level: 1 })).toHaveText('Ben Carter — Annual leave: 26 days 4 h left');
  await expect(page.locator('main')).toContainText("From 8 Oct 2026 Ben Carter's days are 6 h, so 160 h is 26 days 4 h.");
  await openDetails(page, 'Details');
  await expect(page.locator('table').last()).toContainText('Basis');
});
